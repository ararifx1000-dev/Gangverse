-- AYTx app database setup
-- Run this once in Supabase SQL Editor for project qverihfqvbqljctwppos.

alter table public.profiles add column if not exists avatar_url text;

create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  receiver_id uuid not null references auth.users(id) on delete cascade,
  message text not null check (char_length(trim(message)) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists direct_messages_pair_time on public.direct_messages(sender_id, receiver_id, created_at);

create table if not exists public.general_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  message text not null check (char_length(trim(message)) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists general_messages_time on public.general_messages(created_at);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 120),
  description text not null default '',
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.news_posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  caption text not null default '' check (char_length(caption) <= 1500),
  image_url text,
  created_at timestamptz not null default now()
);
create index if not exists news_posts_time on public.news_posts(created_at desc);

alter table public.direct_messages enable row level security;
alter table public.general_messages enable row level security;
alter table public.events enable row level security;
alter table public.news_posts enable row level security;

drop policy if exists "Members read own direct messages" on public.direct_messages;
create policy "Members read own direct messages" on public.direct_messages for select to authenticated
using (auth.uid() = sender_id or auth.uid() = receiver_id);
drop policy if exists "Members send own direct messages" on public.direct_messages;
create policy "Members send own direct messages" on public.direct_messages for insert to authenticated
with check (auth.uid() = sender_id and sender_id <> receiver_id);

drop policy if exists "Members read general messages" on public.general_messages;
create policy "Members read general messages" on public.general_messages for select to authenticated using (true);
drop policy if exists "Members send own general messages" on public.general_messages;
create policy "Members send own general messages" on public.general_messages for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Members read events" on public.events;
create policy "Members read events" on public.events for select to authenticated using (true);
drop policy if exists "Admins create events" on public.events;
create policy "Admins create events" on public.events for insert to authenticated
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and lower(coalesce(p.role,'')) in ('owner','admin','super admin')));

drop policy if exists "Members read news" on public.news_posts;
create policy "Members read news" on public.news_posts for select to authenticated using (true);
drop policy if exists "Members create own news" on public.news_posts;
create policy "Members create own news" on public.news_posts for insert to authenticated
with check (auth.uid() = user_id);
drop policy if exists "Members delete own news" on public.news_posts;
create policy "Members delete own news" on public.news_posts for delete to authenticated
using (auth.uid() = user_id or exists (select 1 from public.profiles p where p.id = auth.uid() and lower(coalesce(p.role,'')) in ('owner','admin','super admin')));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('aytx-media', 'aytx-media', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Authenticated members upload AYTx media" on storage.objects;
create policy "Authenticated members upload AYTx media" on storage.objects for insert to authenticated
with check (bucket_id = 'aytx-media');
drop policy if exists "AYTx media is public" on storage.objects;
create policy "AYTx media is public" on storage.objects for select to public
using (bucket_id = 'aytx-media');

